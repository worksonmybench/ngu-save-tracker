"""Generate src/data/itemNames.ts from the extracted item table. Names only: descriptions stay out of the app.

Usage: python tools/gen_item_names.py ../rea-test/extracted/items.json
"""
import json, os, re, sys

items = json.load(open(sys.argv[1], encoding="utf-8"))
names = [""] * (max(map(int, items)) + 1)
for key, item in items.items():
    name = item.get("itemName") or ""
    name = "" if name == "null" else re.sub(r"</?(b|i|color)\b[^>]*>", "", name)  # rich-text tags, but not "<3"
    names[int(key)] = " ".join(name.split())

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data", "itemNames.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_item_names.py from build 1260. Index = item id.\n")
    f.write("export const ITEM_NAMES: readonly string[] = [\n")
    for name in names:
        f.write(f"  {json.dumps(name, ensure_ascii=False)},\n")
    f.write("];\n\n")
    f.write("export const itemName = (id: number) => ITEM_NAMES[id] || `Item ${id}`;\n")
