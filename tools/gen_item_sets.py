"""Generate src/data/itemSets.ts from the extracted set table. Set flags and item ids only: names come from itemNames.ts.

Usage: python tools/gen_item_sets.py ../rea-test/extracted/item_sets.csv
"""
import csv, json, os, re, sys

# Where splitting the game's "maxxed..." condition name doesn't read well.
NAMES = {"RingUUG": "UUG's Rings", "Bread": "Breadverse", "70sZone": "70s Zone", "2D": "2D Universe",
         "NormalBonusAcc": "Normal bonus accessories", "EvilBonusAcc": "Evil bonus accessories", "JRPG": "JRPG"}

rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8")))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data", "itemSets.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_item_sets.py from build 1260.\n")
    f.write("// [itemList flag, set name, item ids]. A set is complete once every item in it is maxed.\n")
    f.write("export const ITEM_SETS: readonly (readonly [string, string, readonly number[]])[] = [\n")
    for r in rows:
        key = r["condition"].removeprefix("maxxed")
        name = NAMES.get(key) or re.sub(r"(?<=[a-z])(?=[A-Z0-9])", " ", key)
        ids = ", ".join(r["itemIds"].split())
        f.write(f"  [{json.dumps(r['flag'])}, {json.dumps(name)}, [{ids}]],\n")
    f.write("];\n")
