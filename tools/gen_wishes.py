"""Generate src/data/wishes.ts from the extracted wish table. Names and numbers only: descriptions stay out of the app.

Usage: python tools/gen_wishes.py ../rea-test/extracted/wishes.csv
"""
import csv, json, os, sys

DIFFICULTY = {"Evil": 1, "Sadistic": 2}

rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8")))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data", "wishes.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_wishes.py from build 1260. Index = wish id.\n")
    f.write("// [name, difficulty (1 = Evil, 2 = Sadistic), max level, speed divider]\n")
    f.write("export const WISHES: readonly (readonly [string, number, number, number])[] = [\n")
    for r in rows:
        name = " ".join(r["name"].split())
        divider = float(r["speedDivider"])
        f.write(f"  [{json.dumps(name, ensure_ascii=False)}, {DIFFICULTY[r['difficulty']]}, {int(r['maxLevel'])}, {divider:g}],\n")
    f.write("];\n")
